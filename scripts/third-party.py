#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_NOTICES.md and THIRD_PARTY_LICENSES.txt.

    python3 scripts/third-party.py

Covers what ends up in a released binary: the Rust crates linked into the
Linux and Windows builds (normal dependencies only, no build or dev ones), the
npm packages bundled into the frontend, and the projects our parsers were
adapted from. Needs `cargo` and an installed frontend/node_modules, because
the license texts are read from the downloaded packages.
"""

import hashlib
import json
import re
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = ["x86_64-unknown-linux-gnu", "x86_64-pc-windows-msvc", "i686-pc-windows-msvc"]
LICENSE_NAMES = ("license", "licence", "copying", "notice", "unlicense", "copyright")

# Source we adapted or ported by hand. Not a dependency, so no tool finds it.
ADAPTED = [
    ("hlbsp-viewer", "https://github.com/r4v3n6101/hlbsp-viewer", "GPL-3.0",
     "r4v3n6101", "BSP parsing in crates/formats/src/bsp.rs"),
    ("hlbsp", "https://github.com/bernhardmgruber/hlbsp", "BSL-1.0",
     "Bernhard Manfred Gruber", "lightmap extent and atlas UV math in crates/formats/src/bsp.rs"),
    ("Lambda", "https://github.com/KarloSiric/Lambda", "MIT",
     "Copyright (c) 2025 Karlo Siric", "MDL parsing and bone/animation math in crates/formats/src/mdl.rs"),
    ("web-hlmv", "https://github.com/danakt/web-hlmv", "MIT",
     "Copyright (c) 2019 Danakt Frost", "MDL to Three.js render wiring in the frontend"),
]

PLATFORM = [
    ("WebView2 loader", "Microsoft", "BSD-3-Clause",
     "linked statically into the Windows builds through the webview2-com-sys crate"),
    ("Microsoft Visual C++ runtime", "Microsoft", "Visual Studio redistributable terms",
     "linked statically into the Windows builds"),
    ("WebView2 runtime", "Microsoft", "Microsoft terms",
     "used from the user's system on Windows, not distributed with goldview"),
    ("WebKitGTK and GTK 3", "WebKit and GNOME projects", "LGPL-2.1-or-later and BSD",
     "used from the user's system on Linux, not distributed with goldview"),
]


def license_texts(directory):
    """License-like files at the top of a package, as (filename, text)."""
    out = []
    for f in sorted(Path(directory).iterdir()):
        if f.is_file() and f.name.lower().startswith(LICENSE_NAMES):
            out.append((f.name, f.read_text(errors="replace").strip()))
    return out


def rust_packages():
    found = {}
    for target in TARGETS:
        meta = json.loads(subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--filter-platform", target],
            cwd=ROOT))
        packages = {p["id"]: p for p in meta["packages"]}
        nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        root = next(p["id"] for p in meta["packages"] if p["name"] == "goldview")
        seen, stack = set(), [root]
        while stack:
            pkg = stack.pop()
            if pkg in seen:
                continue
            seen.add(pkg)
            for dep in nodes[pkg]["deps"]:
                if any(kind["kind"] is None for kind in dep["dep_kinds"]):
                    stack.append(dep["pkg"])
        for pkg in seen - set(meta["workspace_members"]):
            p = packages[pkg]
            found[(p["name"], p["version"])] = {
                "name": p["name"], "version": p["version"],
                "license": re.sub(r"\s*/\s*", " OR ", p["license"] or "see license file"),
                "url": p["repository"] or f"https://crates.io/crates/{p['name']}",
                "texts": license_texts(Path(p["manifest_path"]).parent),
            }
    return [found[k] for k in sorted(found)]


def npm_packages():
    lock = json.loads((ROOT / "frontend/package-lock.json").read_text())
    out = []
    for path, p in sorted(lock["packages"].items()):
        if not path or p.get("dev") or p.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        out.append({
            "name": name, "version": p["version"], "license": p.get("license", "see license file"),
            "url": f"https://www.npmjs.com/package/{name}",
            "texts": license_texts(ROOT / "frontend" / path),
        })
    return out


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def main():
    rust, npm = rust_packages(), npm_packages()
    counts = Counter(p["license"] for p in rust + npm)

    notices = f"""# Third-party notices

goldview is licensed under GPL-3.0-or-later (see `LICENSE`). It builds on the
work below. This file is generated by `scripts/third-party.py`; the full
license texts are in `THIRD_PARTY_LICENSES.txt`.

## Adapted source

Code we ported or adapted by hand rather than pulling in as a dependency.

{table(["Project", "License", "Author", "Used for"],
       [[f"[{n}]({u})", lic, who, what] for n, u, lic, who, what in ADAPTED])}

The GoldSrc file formats themselves (BSP v30, WAD3, studio model, sprite) were
defined by Valve and id Software. goldview reads those formats and ships no
game assets.

## Platform components

{table(["Component", "Owner", "License", "How it is used"], [list(r) for r in PLATFORM])}

## Licenses in use

{table(["License", "Packages"], [[lic, str(n)] for lic, n in counts.most_common()])}

## Frontend packages (npm), {len(npm)}

{table(["Package", "Version", "License"],
       [[f"[{p['name']}]({p['url']})", p["version"], p["license"]] for p in npm])}

## Rust crates, {len(rust)}

Crates linked into the Linux and Windows release binaries.

{table(["Crate", "Version", "License"],
       [[f"[{p['name']}]({p['url']})", p["version"], p["license"]] for p in rust])}
"""
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text(notices)

    # Identical texts (most Apache-2.0 copies) are printed once with every
    # package that ships them listed above the text.
    users, bodies, missing = defaultdict(list), {}, []
    for p in npm + rust:
        if not p["texts"]:
            missing.append(f"{p['name']} {p['version']} ({p['license']})")
        for filename, text in p["texts"]:
            digest = hashlib.sha256(" ".join(text.split()).encode()).hexdigest()
            bodies[digest] = text
            users[digest].append(f"{p['name']} {p['version']} ({filename})")

    rule = "=" * 78
    parts = ["Full license texts for the packages listed in THIRD_PARTY_NOTICES.md.\n"
             "Generated by scripts/third-party.py.\n"]
    if missing:
        parts.append("Packages that ship no license file. Their license is the SPDX\n"
                     "identifier shown, as declared in the package metadata:\n\n"
                     + "\n".join(f"  {m}" for m in missing) + "\n")
    for digest in sorted(users, key=lambda d: users[d]):
        parts.append(rule + "\n" + "\n".join(users[digest]) + "\n" + rule + "\n\n" + bodies[digest] + "\n")
    (ROOT / "THIRD_PARTY_LICENSES.txt").write_text("\n".join(parts))

    print(f"{len(rust)} crates, {len(npm)} npm packages, {len(users)} distinct license texts, "
          f"{len(missing)} without a license file")


if __name__ == "__main__":
    main()
